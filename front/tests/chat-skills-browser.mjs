// Isolated browser verification: every API and WebSocket is intercepted with synthetic data.
// PLAYWRIGHT_MODULE may point to an existing local Playwright installation.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const skills=JSON.parse(fs.readFileSync(new URL('../../backed/Resources/ChatSkills/catalog-v1.json',import.meta.url)));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage(); const sent=[]; const errors=[];
await page.addInitScript(() => localStorage.setItem('aiagent.frontend-onboarding.completed','true'));
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/api/**',async route=>{
 const path=new URL(route.request().url()).pathname;
 let body=[];
 if(path==='/api/v1/auth/status')body={authenticated:true,user_id:'skill-test',username:'skill-test',is_admin:false};
 else if(path==='/api/v1/settings')body={ui:{theme:'light',language:'zh',preferred_agent:'none'},catalog:{version:1,services:{llm:{active_profile_id:'test',active_model_id:'test',profiles:[{id:'test',name:'Test',models:[{id:'test',name:'Test',model:'test'}]}]}}}};
 else if(path==='/api/v1/settings/ui')body={theme:'light',language:'zh'};
 else if(path==='/api/v1/chat/skills')body=skills;
 else if(path.endsWith('/sessions/list'))body={sessions:[]};
 else if(path.endsWith('/sessions/project-preferences'))body={preferences:[]};
 else if(path.endsWith('/sessions/sidebar-preference'))body={project_sort_mode:'name'};
 else if(/\/sessions\/[^/]+$/.test(path))body={id:path.split('/').at(-1),title:'Test',messages:[],preferences:{},project_id:null};
 else if(path.includes('codex-model-policy'))body={models:[],allowed_model_ids:[]};
 else if(path.includes('image-ocr'))body={};
 await route.fulfill({json:body});
});
await page.routeWebSocket('**/api/v1/chat/ws',ws=>ws.onMessage(message=>{
 sent.push(JSON.parse(String(message)));
 ws.send(JSON.stringify({type:'content',content:'这是合成测试响应'}));
 ws.send(JSON.stringify({type:'completed'}));
}));
try{
 await page.goto(process.env.CHAT_TEST_URL||'http://127.0.0.1:3799/chat');
 const editor=page.locator('[contenteditable=true]:visible').first();
 await editor.waitFor({timeout:60000});
 await editor.fill('/追问');
 await page.getByRole('listbox',{name:'主动调用技能'}).waitFor();
 await page.getByRole('listbox',{name:'主动调用技能'}).getByRole('option').first().waitFor();
 assert.equal(await page.getByRole('listbox',{name:'主动调用技能'}).getByRole('option').count(),1);
 await page.getByRole('button',{name:'预览',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 assert.match(await page.getByRole('dialog').innerText(),/每次只追问/);
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 await editor.focus(); await editor.press('Enter');
 assert.equal(sent.length,0,'selecting must not submit');
 await page.getByRole('button',{name:'结束技能'}).waitFor();
 await editor.fill('我想修改知识库'); await editor.press('Enter');
 await page.waitForTimeout(700);
 assert.equal(sent[0]?.skill_invocation?.id,'grill-me');
 await page.getByRole('button',{name:'结束技能'}).waitFor();
 await editor.fill('主要是目录不好找'); await editor.press('Enter');
 await page.waitForTimeout(700);
 assert.equal(sent.length,2,'follow-up must be submitted');
 assert.equal(sent[1]?.skill_invocation?.id,'grill-me','a visible active flow continues');
 await page.getByRole('button',{name:'结束技能'}).click();
 await editor.fill('普通消息'); await editor.press('Enter');
 await page.waitForTimeout(700);
 assert.equal(sent.length,3,'ordinary message must be submitted');
 assert.equal(sent[2]?.skill_invocation,undefined,'ending must remove the selection');
 await editor.fill('/to-spec 保留这个草稿'); await editor.press('Tab');
 assert.equal(await editor.innerText(),'保留这个草稿');
 await editor.press('Enter'); await page.waitForTimeout(700);
 assert.equal(sent[3]?.skill_invocation?.id,'to-spec');
 assert.equal(await page.getByRole('button',{name:'移除',exact:true}).count(),0,'one-shot selection clears after sending');
 await editor.fill('/');
 await page.getByRole('button',{name:'搜索项目 / 文档 →'}).click();
 await page.getByRole('listbox',{name:'引用其他项目'}).waitFor();
 await editor.press('Escape');
 await page.setViewportSize({width:390,height:844});
 const mobile=page.locator('[contenteditable=true]:visible').first();
 await mobile.fill('/teach');
 const menu=page.getByRole('listbox',{name:'主动调用技能'}); await menu.waitFor();
 const box=await menu.boundingBox(); assert.ok(box.x>=0&&box.x+box.width<=390);
 await menu.getByRole('option').click();
 await page.getByRole('button',{name:'结束技能'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('Browser passed: Chinese search, preview, keyboard select without send, explicit request, multi-turn session creation, end, draft preservation, project menu, mobile bounds.');
}finally{await browser.close();}
