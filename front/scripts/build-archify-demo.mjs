// Run with a clean checkout of https://github.com/tt-a1i/archify at the pinned commit.
// No dependency installation or network access is needed during generation.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, renameSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const revision = "73aaa0696e8f72c232ea710e6fa94fd953f3e773";
const checkout = process.argv[2];
if (!checkout) throw new Error("Usage: node scripts/build-archify-demo.mjs <archify-checkout>");
const upstream = path.resolve(checkout);
const git = (...args) => execFileSync("git", ["-C", upstream, ...args], { encoding: "utf8" }).trim();
if (git("rev-parse", "HEAD") !== revision || git("status", "--porcelain")) {
  throw new Error(`Archify must be a clean checkout at ${revision}`);
}
const output = fileURLToPath(new URL("../public/archify/", import.meta.url));
const temporary = mkdtempSync(path.join(tmpdir(), "aiagent-archify-"));
const publish = (name, content) => {
  const target = path.join(output, name);
  writeFileSync(`${target}.tmp`, content, "utf8");
  renameSync(`${target}.tmp`, target);
};
try {
  const htmlPath = path.join(temporary, "demo.html");
  execFileSync(process.execPath, [
    path.join(upstream, "archify/renderers/architecture/render-architecture.mjs"),
    path.join(output, "aiagent-demo.architecture.json"), htmlPath,
  ], { stdio: "inherit" });
  let html = readFileSync(htmlPath, "utf8");
  // Keep the fixed viewer offline, including when opened as a standalone page.
  const policy = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; font-src data:; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'";
  html = html.replace("<head>", `<head>\n<meta http-equiv="Content-Security-Policy" content="${policy}">`);
  const license = readFileSync(path.join(upstream, "LICENSE"), "utf8");
  html = html.replace("</head>", `<!-- Generated by Archify ${revision}.\n${license}-->\n</head>`);
  publish("aiagent-demo.html", html);
  publish("LICENSE.txt", license);
  publish("THIRD_PARTY_NOTICES.md", readFileSync(path.join(upstream, "archify/THIRD_PARTY_NOTICES.md"), "utf8"));
  publish("JetBrainsMono-OFL.txt", readFileSync(path.join(upstream, "archify/assets/JetBrainsMono-OFL.txt"), "utf8"));
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
